// Generates src/lib/icons.generated.ts from the Iconify JSON packages.
// Icon names match the layer names used in the Figma design.
import { readFileSync, writeFileSync } from "node:fs";

const wanted = {
  hugeicons: [
    "python", "react", "tailwindcss",
    "code", "code-xml", "location-01", "at", "time-04", "phone", "copy-01",
    "cloud", "boxes", "unfold-more", "unfold-less", "link-01", "infinity-01",
    "search-01", "moon", "new-twitter", "github-01", "linkedin-01", "discord",
    "youtube", "badge-check", "tick-02", "arrow-left-01", "arrow-right-01", "moon-02",
    // Search menu
    "home-01", "file-01", "hashtag", "puzzle", "layout-02", "news", "arrow-up-right-01",
    "mail-01", "layers-01", "briefcase-01", "graduation-scroll", "user", "contact-01",
    // Theme
    "sun-01", "computer",
  ],
  "akar-icons": [
    "nextjs-fill", "postgresql-fill", "github-fill", "vercel-fill", "linkedin-box-fill",
    "youtube-fill", // the design uses solid GitHub, LinkedIn and YouTube marks
  ],
  bxl: [
    "shadcn-ui", "motion-js", "mongodb", "prisma-orm", "cursor-ai", "kubernetes",
    "typescript", "javascript", // the design uses the solid TS / JS squares
  ],
  "devicon-plain": ["nodejs-wordmark"],
  devicon: ["socketio"],
  "griddy-icons": ["expressjs"],
  bi: ["openai", "git", "patch-check-fill"], // patch-check-fill = the solid verified seal
  "ant-design": ["claude-filled", "gemini-filled", "docker-outlined"],
  basil: ["figma-solid"],
};

const out = {};
for (const [set, names] of Object.entries(wanted)) {
  const j = JSON.parse(readFileSync(`node_modules/@iconify-json/${set}/icons.json`, "utf8"));
  for (const n of names) {
    let key = n;
    let icon = j.icons[key];
    if (!icon && j.aliases?.[key]) {
      const a = j.aliases[key];
      icon = { ...j.icons[a.parent], ...a };
    }
    if (!icon) throw new Error(`Missing icon ${set}:${n}`);
    out[`${set}:${n}`] = {
      body: icon.body,
      // Iconify's default is a 16-unit box, not 24, when a set doesn't say.
      // Guessing 24 made every 16-unit icon (e.g. bi:*) draw a third too small.
      w: icon.width ?? j.width ?? 16,
      h: icon.height ?? j.height ?? 16,
    };
  }
}

// Icons the design draws that no icon set ships, derived from ones that do.
const sun = out["hugeicons:sun-01"];
out["custom:sun-solid"] = {
  // The design's light-mode toggle is sun-01 with a solid centre.
  body: `${sun.body}<circle cx="12" cy="12" r="5" fill="currentColor"/>`,
  w: sun.w,
  h: sun.h,
};

const src = `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit by hand.
export type IconData = { body: string; w: number; h: number };

export const icons = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, IconData>;

export type IconName = keyof typeof icons;
`;
writeFileSync("src/lib/icons.generated.ts", src);
console.log(`Wrote ${Object.keys(out).length} icons`);
